@dataclass
class RK78Stats:
    accepted_steps: int
    rejected_steps: int
    function_evaluations: int
    final_time: float
    final_state: np.ndarray
    first_attempt_error_norm: float
    first_accepted_step: float


def _as_1d_float_array(values: np.ndarray) -> np.ndarray:
    return np.asarray(values, dtype=float).reshape(-1)


def _build_stage(
    y_base: np.ndarray,
    h: float,
    stage_weights: np.ndarray,
    stage_values: np.ndarray,
    work: np.ndarray,
) -> np.ndarray:
    work[:] = y_base
    if stage_weights.size:
        work += h * np.dot(stage_weights, stage_values)
    return work


def _compute_error_vector(y8: np.ndarray, y7: np.ndarray) -> np.ndarray:
    return y8 - y7


def _compute_error_norm(error_vec: np.ndarray, scale: np.ndarray) -> float:
    scaled_error = error_vec / scale
    return float(np.sqrt(np.mean(scaled_error * scaled_error)))


def _initial_step_size(
    y0: np.ndarray,
    f0: np.ndarray,
    rel_tol: float,
    abs_tol: float,
    max_step: float,
    remaining: float,
    requested_step: float | None,
) -> float:
    if requested_step is not None:
        step = abs(float(requested_step))
        if step <= 0.0:
            raise ValueError("InternalStep/InitialStep must be positive when provided.")
        return min(step, max_step, remaining)

    heuristic_step = 1e-3

    if y0.size >= 6 and np.linalg.norm(y0[:3]) > 0.0 and np.linalg.norm(f0[3:6]) > 0.0:
        radius = float(np.linalg.norm(y0[:3]))
        speed = float(np.linalg.norm(y0[3:6]))
        acceleration = float(np.linalg.norm(f0[3:6]))
        orbital_timescale = radius / max(speed, 1e-12)
        acceleration_timescale = np.sqrt(radius / max(acceleration, 1e-12))
        heuristic_step = min(heuristic_step, 0.01 * min(orbital_timescale, acceleration_timescale))

    return min(max(heuristic_step, 1e-6), max_step, remaining)


def _rk78_step(
    fun: Callable[[float, np.ndarray], np.ndarray],
    t_current: float,
    y_current: np.ndarray,
    f_current: np.ndarray,
    h: float,
    stage_values: np.ndarray,
    y_work: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, int]:
    stage_values[0] = f_current

    for stage_index in range(1, RK78_C.size):
        y_stage = _build_stage(
            y_current,
            h,
            RK78_A[stage_index, :stage_index],
            stage_values[:stage_index],
            y_work,
        )
        stage_values[stage_index] = _as_1d_float_array(fun(t_current + RK78_C[stage_index] * h, y_stage))

    y8 = y_current + h * np.dot(RK78_B8, stage_values)
    y7 = y_current + h * np.dot(RK78_B7, stage_values)
    error_vec = _compute_error_vector(y8, y7)
    return y8, error_vec, RK78_C.size - 1


def rk78_integrate(
    fun: Callable[[float, np.ndarray], np.ndarray],
    t_eval: np.ndarray,
    y0: np.ndarray,
    options: dict | None = None,
) -> tuple[np.ndarray, np.ndarray, RK78Stats]:
    """Integrate to requested output times using a standalone adaptive Prince-Dormand RK7(8) stepper.

    Step size is clamped so the solver lands on (or exactly reaches) each requested
    time in `t_eval` without overshooting beyond the next requested output time.
    """
    if options is None:
        options = {}

    rel_tol = float(options.get("RelTol", 1e-12))
    abs_tol = float(options.get("AbsTol", 1e-14))
    max_step = float(options.get("MaxStep", 60.0))
    requested_step = options.get("InternalStep", options.get("InitialStep", options.get("FirstStep")))

    if max_step <= 0.0:
        raise ValueError("MaxStep must be positive.")

    t_eval = np.asarray(t_eval, dtype=float).reshape(-1)
    if t_eval.size < 2:
        raise ValueError("t_eval must contain at least two time points.")

    direction = np.sign(t_eval[-1] - t_eval[0])
    if direction == 0:
        raise ValueError("t_eval must span a nonzero time interval.")

    if np.any(np.diff(t_eval) * direction <= 0):
        raise ValueError("t_eval must be strictly monotonic.")

    y_current = _as_1d_float_array(y0)
    if y_current.size == 0:
        raise ValueError("y0 must contain at least one state component.")

    t_current = float(t_eval[0])
    t_final = float(t_eval[-1])

    # Pre-allocate output aligned with t_eval
    y_out = np.empty((t_eval.size, y_current.size), dtype=float)
    y_out[0] = y_current

    f_current = _as_1d_float_array(fun(t_current, y_current))
    if f_current.size != y_current.size:
        raise ValueError("fun must return a derivative vector with the same size as y0.")

    function_evaluations = 1
    accepted_steps = 0
    rejected_steps = 0
    first_attempt_error_norm = float("nan")
    first_accepted_step = float("nan")

    stage_values = np.empty((RK78_C.size, y_current.size), dtype=float)
    y_work = np.empty_like(y_current)

    needs_f_eval = False
    h_abs = _initial_step_size(
        y_current,
        f_current,
        rel_tol,
        abs_tol,
        max_step,
        abs(t_final - t_current),
        None if requested_step is None else float(requested_step),
    )

    output_index = 1
    while output_index < t_eval.size:
        remaining_to_final = t_final - t_current
        if direction * remaining_to_final <= 0.0:
            break

        next_output_time = float(t_eval[output_index])

        # Clamp by the next requested output time (and final time/max_step)
        h_abs = min(
            h_abs,
            max_step,
            abs(remaining_to_final),
            abs(next_output_time - t_current),
        )

        if h_abs == 0.0:
            # Already at the next requested time (within float resolution)
            y_out[output_index] = y_current
            output_index += 1
            continue

        h = direction * h_abs
        t_new = t_current + h

        # Final-time safety clamp
        if direction * (t_new - t_final) > 0.0:
            t_new = t_final
            h = t_new - t_current
            h_abs = abs(h)

        # Ensure f_current is available
        if needs_f_eval:
            f_current = _as_1d_float_array(fun(t_current, y_current))
            if f_current.size != y_current.size:
                raise ValueError("fun must return a derivative vector with the same size as y0.")
            function_evaluations += 1
            needs_f_eval = False

        y8, error_vec, stage_evaluations = _rk78_step(
            fun,
            t_current,
            y_current,
            f_current,
            h,
            stage_values,
            y_work,
        )
        function_evaluations += stage_evaluations

        scale = np.full_like(y_current, abs_tol, dtype=float) + rel_tol * np.abs(y8)
        error_norm = _compute_error_norm(error_vec, scale)
        if np.isnan(first_attempt_error_norm):
            first_attempt_error_norm = error_norm

        if error_norm <= 1.0:
            accepted_steps += 1
            if np.isnan(first_accepted_step):
                first_accepted_step = abs(h)

            # Accept step
            t_current = t_new
            y_current = y8
            needs_f_eval = True  # will compute f at updated state for the next step

            # Fill all outputs reached (typically exactly one due to clamping)
            while output_index < t_eval.size:
                target_time = float(t_eval[output_index])
                output_ready = (direction > 0.0 and target_time <= t_current) or (
                    direction < 0.0 and target_time >= t_current
                )
                if not output_ready:
                    break
                y_out[output_index] = y_current
                output_index += 1

            if error_norm == 0.0:
                factor = MAX_FACTOR
            else:
                factor = SAFETY * error_norm ** (-1.0 / 8.0)
                factor = min(MAX_FACTOR, max(MIN_FACTOR, factor))

            h_abs = min(max_step, abs(h) * factor)
        else:
            rejected_steps += 1
            factor = SAFETY * error_norm ** (-1.0 / 8.0)
            h_abs = min(max_step, abs(h) * max(MIN_FACTOR, factor))

    if output_index < t_eval.size:
        raise RuntimeError("RK78 integration failed to reach the final output time.")

    stats = RK78Stats(
        accepted_steps=accepted_steps,
        rejected_steps=rejected_steps,
        function_evaluations=function_evaluations,
        final_time=float(t_current),
        final_state=y_current.copy(),
        first_attempt_error_norm=first_attempt_error_norm,
        first_accepted_step=first_accepted_step,
    )

    return t_eval, y_out, stats
    return t_eval, y_out, stats
